export function getCurrentDincharyaPhase(hour: number): PhaseDetails {
  if (hour >= 4 && hour < 6) return DINCHARYA_PHASES[0]; // Pratah
  if (hour >= 6 && hour < 9) return DINCHARYA_PHASES[1]; // Vyayama
  if (hour >= 9 && hour < 14) return DINCHARYA_PHASES[2]; // Madhyanha
  if (hour >= 14 && hour < 17) return DINCHARYA_PHASES[3]; // Aparanha
  if (hour >= 17 && hour < 20) return DINCHARYA_PHASES[4]; // Sandhya
  return DINCHARYA_PHASES[5]; // Ratri
}
